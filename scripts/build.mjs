#!/usr/bin/env node
/**
 * Build lib/*.js from src/*.ts with Node's built-in type stripper.
 *
 * The package intentionally has no build dependency: DSH loads `lib/` directly,
 * and Node >= 22.6 ships `module.stripTypeScriptTypes()`. Sources use only
 * erasable TypeScript syntax (no enums, namespaces, parameter properties).
 */

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stripTypeScriptTypes } from 'node:module'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const srcDir = join(root, 'src')
const outDir = join(root, 'lib')
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const banner = '// GENERATED from src/%s by scripts/build.mjs — do not edit this file directly.\n'
let count = 0
for (const name of readdirSync(srcDir)) {
  if (!name.endsWith('.ts')) continue
  const source = readFileSync(join(srcDir, name), 'utf8')
  const output = stripTypeScriptTypes(source, { mode: 'strip' })
  const target = name.replace(/\.ts$/u, '.js')
  writeFileSync(join(outDir, target), banner.replace('%s', name) + output, 'utf8')
  count += 1
}
process.stdout.write(`built ${count} module(s) into lib/\n`)