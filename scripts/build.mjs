#!/usr/bin/env node
/**
 * Build lib/**\/*.js from src/**\/*.ts with Node's built-in type stripper.
 *
 * The package intentionally has no build dependency: DSH loads `lib/` directly,
 * and Node >= 22.6 ships `module.stripTypeScriptTypes()`. Sources use only
 * erasable TypeScript syntax (no enums, namespaces, parameter properties).
 *
 * ── SUBDIRECTORIES (step 0 of the store.ts split, 2026-11-14) ──────────────────────────────────
 *
 * This script originally did `for (const name of readdirSync(srcDir))` — TOP LEVEL ONLY.
 * The first subdirectory anywhere under `src/` therefore produced a module that was never compiled:
 * `src/store/clock.ts` existed, `store.ts` imported `./store/clock.js`, and the build still printed
 * "built 27 module(s)" because it never saw the new file. At runtime that surfaces as
 *
 *     ERR_MODULE_NOT_FOUND: lib/store/clock.js
 *
 * — a failure that looks like a broken import rather than a build script that skipped a file.
 *
 * So: walk `src/` recursively, mirror the directory structure into `lib/`.
 * The output count is a real count now (27 → 28 after the first subdirectory).
 */

import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stripTypeScriptTypes } from 'node:module'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const srcDir = join(root, 'src')
const outDir = join(root, 'lib')
rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

/** Every `.ts` under `src/`, as paths relative to `src/` (posix separators). */
function walk (dir, out = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) walk(full, out)
    else if (entry.name.endsWith('.ts')) out.push(relative(srcDir, full).split('\\').join('/'))
  }
  return out
}

const banner = '// GENERATED from src/%s by scripts/build.mjs — do not edit this file directly.\n'
let count = 0
for (const rel of walk(srcDir).sort()) {
  const source = readFileSync(join(srcDir, rel), 'utf8')
  const output = stripTypeScriptTypes(source, { mode: 'strip' })
  const target = rel.replace(/\.ts$/u, '.js')
  const targetPath = join(outDir, target)
  mkdirSync(dirname(targetPath), { recursive: true })
  writeFileSync(targetPath, banner.replace('%s', rel) + output, 'utf8')
  count += 1
}
process.stdout.write(`built ${count} module(s) into lib/\n`)
